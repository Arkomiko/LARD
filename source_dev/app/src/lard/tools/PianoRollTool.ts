/**
 * Инструменты пианоролла.
 *
 * Набор и буквы горячих клавиш взяты из FL Studio, чтобы руки, привыкшие
 * к FL, работали здесь без переучивания:
 *
 *   P — Draw   (рисование: ЛКМ ставит ноту, ПКМ удаляет)
 *   B — Paint  (кисть: ноты сыплются по всей протяжке)
 *   D — Delete (ластик: ЛКМ стирает ноты, в том числе протяжкой)
 *   E — Select (рамка выделения)
 *
 * Имена "pencil" и "selection" оставлены прежними: на них завязаны
 * редактор автоматизации и редактор темпа.
 */
export type PianoRollTool = "pencil" | "paint" | "delete" | "selection"

/**
 * Инструмент правит ноты, а не выделяет их.
 *
 * Нужно там, где раньше стояла проверка `mouseMode === "pencil"`: смысл её
 * был «сейчас не режим выделения», и с появлением кисти и ластика прямое
 * сравнение с "pencil" начало врать.
 */
export const isNoteEditTool = (tool: PianoRollTool): boolean =>
  tool !== "selection"

/**
 * Инструмент должен перехватывать нажатия на самих нотах.
 *
 * Кисть — не должна: в FL протяжка поверх существующих нот дописывает
 * аккорд, а не тащит уже стоящую ноту.
 */
export const usesNoteHitAreas = (tool: PianoRollTool): boolean =>
  tool === "pencil" || tool === "delete"
