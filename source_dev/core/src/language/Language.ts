/**
 * Формат перевода LARD.
 *
 * Язык — файл `<код>.ts` в папке `Language` в корне репозитория: словарь
 * «ключ строки → перевод» и отдельный экспорт `label` с названием языка на нём
 * самом. Полный набор ключей задаёт английский, остальные могут покрывать его
 * частично — недостающие строки остаются английскими.
 *
 * Ядро не знает, какие именно ключи есть в словаре: набор задаётся файлом
 * английского, а он лежит вне ядра. Поэтому тип базового словаря — параметр.
 */

/** Перевод: покрывает не обязательно все ключи базового словаря. */
export type Translation<TBase> = Partial<TBase>

/**
 * Код языка. Конкретный набор известен только на этапе сборки — он зависит от
 * того, какие файлы лежат в папке `Language`, поэтому тип строковый.
 */
export type LanguageCode = string

/** Язык, на который откатываемся: он полный по определению. */
export const defaultLanguageCode = "en"
